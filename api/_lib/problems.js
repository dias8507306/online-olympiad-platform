function addDays(iso, n) {
  const d = new Date(iso + 'T00:00:00Z');
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}

export function todayAlmaty(now = Date.now()) {
  return new Date(now + TZ_OFFSET_HOURS * 3600e3).toISOString().slice(0, 10);
}

// Барлық есептер: id, grp, day, date, ... (answer қоса)
export function allProblems(grp) {
  const g = GROUPS[grp];
  if (!g) return [];
  return LIST[grp].map((p, i) => ({ ...p, id: `${grp}-d${i + 1}`, grp, day: i + 1, date: addDays(g.start, i) }));
}

export function findProblem(id) {
  const grp = String(id).split('-')[0];
  return allProblems(grp).find((p) => p.id === id) || null;
}

export function statusOf(p, today = todayAlmaty()) {
  if (p.date === today) return 'open';
  return p.date < today ? 'closed' : 'upcoming';
}

// Ата-анаға көрсетілетін нұсқа: жауапсыз, болашақ есептің мәтінісіз.
export function publicProblems(grp, today = todayAlmaty()) {
  return allProblems(grp).map((p) => {
    const status = statusOf(p, today);
    const base = { id: p.id, day: p.day, date: p.date, status };
    if (status === 'upcoming') return base;
    return { ...base, type: p.type, rows: p.rows, kk: p.kk, ru: p.ru };
  });
}

export function groupOfGrade(grade) {
  const n = Number(grade);
  return Object.keys(GROUPS).find((k) => GROUPS[k].grades.includes(n)) || null;
}

// Жауапты санға айналдыру. Тек БІР сан болуы керек, әйтпесе null.
//  "57", " 57 ", "1 275", "1275 тг", "75°", "1,275" (мыңдық) → сан
//  "2,5" / "2.5" → 2.5;  "57 немесе 58", "абв" → null
export function parseAnswer(raw) {
  let s = String(raw ?? '').trim();
  s = s.replace(/(\d)[\s  ]+(?=\d{3}\b)/g, '$1');      // 1 275 → 1275
  s = s.replace(/^(-?\d{1,3})[,.](\d{3})(?!\d)(?![,.]\d)/, '$1$2'); // 1,275 → 1275
  s = s.replace(/(\d),(\d)/g, '$1.$2');                            // 2,5 → 2.5
  const nums = s.match(/-?\d+(?:\.\d+)?/g);
  if (!nums || nums.length !== 1) return null;
  const v = Number(nums[0]);
  return Number.isFinite(v) ? v : null;
}

export function isCorrect(p, raw) {
  const v = parseAnswer(raw);
  return v !== null && Math.abs(v - p.answer) < 1e-9;
}
